def generate_grid_params(data_x, data_y, proj_str):
    ''' given x and y values for data, and projection string, return grid parameters'''
    grid = np.meshgrid(data_x,data_y)
    projn = pyproj.Proj(proj_str)
    lons, lats = projn(grid[0],grid[1],inverse=True)
    return lons, lats, projn, grid 
    
def generate_snowmodel_grid(sm_data):
    # generate grid parameters for snowmodel-lg
    proj_str = '+proj=laea +lat_0=90 +lon_0=0 +x_0=0 +y_0=0 +a=6371228 +b=6371228 +units=m +no_defs'
    return generate_grid_params(sm_data['x'],sm_data['y'], proj_str)

def generate_ic_sk_grid(data): # this can be generalized from snowmodel above if need be
    proj_str = "+proj=stere +lat_0=90 +lat_ts=70 +lon_0=-45 +x_0=0 +y_0=0 +a=6378273 +b=6356889.449 +units=m +no_defs +type=crs"
    return generate_grid_params(data['x']*1000,data['y']*1000, proj_str)

def open_shapefiles_from_list(file_list):
    # given list of filenames, open shapefiles
    shape_list = []
    for f in file_list:
        shape_list.append(geopandas.read_file(f))
    return shape_list

def clip_to_shape_list(model_output, shape_list):
    # clip model_output to geometries in shape_list
    clipped_list = []
    for i,s in enumerate(shape_list):
        clipped_list.append(model_output.rio.clip(s.geometry.apply(mapping), s.crs, all_touched=False,drop=False))
    return clipped_list

def add_crs_and_dates_nesosim(da):
    '''add crs to nesosim and adjust date format'''
    da['x'] = da['xgrid'][0].values
    da['y'] = da['xgrid'][0].values
    da.rio.set_spatial_dims('x', 'y')
    da.rio.write_crs("epsg:3413", inplace=True)
    # add time index
    da['day'] = pd.to_datetime(da['day'],format='%Y%m%d')
    return da

