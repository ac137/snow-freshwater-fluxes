def spatial_avg_df_list(da_list):
    '''calculate spatial average (across dimensions x and y) for each dataarray in da_list
    return list of dataframes of spatial averages of data in da_list
    '''
    avg_list = []
    for da in da_list:
        df = da.mean(dim=['x','y']).to_dataframe()
        avg_list.append(df[[df.columns[-1]]])
    return avg_list

