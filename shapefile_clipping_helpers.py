def save_xr_comp(ds, filename):
    ''' save xarray dataset (ds) with compression to filename'''
    comp = dict(zlib=True, complevel=5)
    encoding = {var: comp for var in ds.data_vars}
    ds.to_netcdf(filename, encoding=encoding)

def load_clipped_data_to_dict(dataset_name, gate_list, variable_list):
    ''' load clipped data generated by batch_clip_to_shapefile_intermediate.ipynb to a dict of dict
    structure: data_dict[gate_name][var_name] where gate_name is from gate_list and var_name is from variable_list'''

    data_dict = {}

    for gate_name in gate_list:
        data_dict[gate_name] = {}
        for var_name in variable_list:
            data_dict[gate_name][var_name] = xr.open_dataset('shapefile_clipped_data/{}_{}_shapefile_clipped_{}.nc'.format(dataset_name, var_name, gate_name))
    return data_dict

def load_and_preprocess_ice_flux_data(flux_fn):
    '''load ice flux data from csv files, drop na, and create datetime index'''
    flux_data = pd.read_csv(flux_fn)
    flux_data = flux_data.dropna(how='all')
    flux_data['Day'] = 1
    flux_data['Date'] = pd.to_datetime(flux_data[['Year','Month','Day']])
    flux_data.index = flux_data['Date']
    return flux_data